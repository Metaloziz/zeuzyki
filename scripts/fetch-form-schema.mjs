// Fetches the Google Form HTML, extracts FB_PUBLIC_LOAD_DATA_ structure,
// and writes a typed TS module to src/generated/form-schema.ts.
//
// Runs before `dev` and `build` via package.json hooks.
// If fetch fails AND a previous snapshot exists, we keep the old snapshot
// so dev/build still works offline. If no snapshot exists, we hard-fail.

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

const FORM_ID = "1FAIpQLSfeFnyoSE8BIR9VuoLfD0oahgNghzNA_7lZm52Plp57aENyyA";
const FORM_URL = `https://docs.google.com/forms/d/e/${FORM_ID}/viewform`;
const OUT_PATH = resolve("src/generated/form-schema.ts");

/** Google Forms internal type codes → semantic names we care about. */
const TYPE_MAP = {
  0: "short",
  1: "paragraph",
  2: "radio",
  3: "dropdown",
  4: "checkbox",
  6: "info",
  8: "section",
};

async function fetchHtml() {
  // Bust HTTP cache + ignore any CDN/edge layer between us and Google.
  const url = `${FORM_URL}?_=${Date.now()}`;
  const res = await fetch(url, {
    cache: "no-store",
    headers: {
      "User-Agent": "zeuzyki-build/1.0",
      "Accept-Language": "ru",
      "Cache-Control": "no-cache, no-store, max-age=0",
      Pragma: "no-cache",
    },
  });
  if (!res.ok) throw new Error(`HTTP ${res.status} ${res.statusText}`);
  return await res.text();
}

function extractRaw(html) {
  const m = html.match(/FB_PUBLIC_LOAD_DATA_\s*=\s*(\[[\s\S]*?\]);<\/script>/);
  if (!m) throw new Error("FB_PUBLIC_LOAD_DATA_ block not found in form HTML.");
  return JSON.parse(m[1]);
}

function parseFields(raw) {
  // raw[1][1] — array of questions
  // raw[3] — form title (sometimes)
  const questionsRaw = raw?.[1]?.[1];
  if (!Array.isArray(questionsRaw)) {
    throw new Error("Unexpected form structure: questions array not found.");
  }

  const fields = [];
  for (const q of questionsRaw) {
    if (!Array.isArray(q)) continue;
    const [internalId, label, , typeCode, answerBlock] = q;
    const type = TYPE_MAP[typeCode] ?? "unknown";

    // Section breaks / info blocks have no entry ID — skip.
    if (!Array.isArray(answerBlock) || answerBlock.length === 0) continue;

    const inner = answerBlock[0];
    if (!Array.isArray(inner)) continue;
    const [entryIdLast, optionsRaw, required] = inner;

    const field = {
      internalId,
      entryId: `entry.${entryIdLast}`,
      type,
      label: String(label ?? "").trim(),
      required: required === 1,
    };

    if (Array.isArray(optionsRaw)) {
      field.options = optionsRaw
        .map((opt) => (Array.isArray(opt) ? opt[0] : null))
        .filter((v) => typeof v === "string");
    }

    fields.push(field);
  }
  return fields;
}

function parseTitle(raw, fields) {
  // Title is often at raw[3] or raw[1][8]. Fall back to a sensible default.
  const candidates = [raw?.[3], raw?.[1]?.[8]];
  const found = candidates.find((v) => typeof v === "string" && v.length > 0);
  return found ?? fields[0]?.label ?? "Google Form";
}

function emit(fields, title) {
  const ts = new Date().toISOString();
  const fieldsLiteral = fields
    .map((f) => {
      const opts = f.options
        ? `,\n    options: [${f.options.map((o) => JSON.stringify(o)).join(", ")}]`
        : "";
      return `  {
    internalId: ${f.internalId},
    entryId: ${JSON.stringify(f.entryId)},
    type: ${JSON.stringify(f.type)},
    label: ${JSON.stringify(f.label)},
    required: ${f.required}${opts},
  }`;
    })
    .join(",\n");

  return `// AUTO-GENERATED by scripts/fetch-form-schema.mjs
// DO NOT EDIT — regenerated on every \`yarn dev\` / \`yarn build\`.
// Source: ${FORM_URL}
// Generated at: ${ts}

export type FormFieldType =
  | 'short'
  | 'paragraph'
  | 'radio'
  | 'dropdown'
  | 'checkbox'
  | 'info'
  | 'section'
  | 'unknown';

export interface FormField {
  internalId: number;
  entryId: string;
  type: FormFieldType;
  label: string;
  required: boolean;
  options?: string[];
}

export const FORM_ID = ${JSON.stringify(FORM_ID)};
export const FORM_URL = ${JSON.stringify(FORM_URL)};
export const FORM_TITLE = ${JSON.stringify(title)};
export const FORM_GENERATED_AT = ${JSON.stringify(ts)};

export const FORM_FIELDS: readonly FormField[] = [
${fieldsLiteral}
] as const;

/** Lookup by entry ID. Returns undefined if not found. */
export function getFormField(entryId: string): FormField | undefined {
  return FORM_FIELDS.find((f) => f.entryId === entryId);
}
`;
}

async function main() {
  let html;
  try {
    html = await fetchHtml();
  } catch (err) {
    if (existsSync(OUT_PATH)) {
      console.warn(
        `[fetch-form-schema] Fetch failed (${err.message}). Using existing snapshot at ${OUT_PATH}.`,
      );
      return;
    }
    console.error(
      `[fetch-form-schema] Fetch failed and no snapshot exists. Cannot continue.\n${err.message}`,
    );
    process.exit(1);
  }

  const raw = extractRaw(html);
  const fields = parseFields(raw);
  const title = parseTitle(raw, fields);

  if (fields.length === 0) {
    console.error(
      "[fetch-form-schema] No fields parsed. Aborting to avoid blanking the app.",
    );
    process.exit(1);
  }

  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, emit(fields, title), "utf8");
  console.log(
    `[fetch-form-schema] Wrote ${OUT_PATH} — ${fields.length} field(s) from "${title}".`,
  );
}

await main();
